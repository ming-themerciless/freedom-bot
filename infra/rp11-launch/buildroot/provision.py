# install
# ---------------------------------------------------------------------------


def read_lock(path: Path) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for line in path.read_text().splitlines():
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, _, v = line.partition("=")
        out.setdefault(k, []).append(v)
    return out


def _ar_members(data: bytes) -> dict[str, bytes]:
    if data[:8] != b"!<arch>\n":
        raise SystemExit("not an ar archive")
    pos, out = 8, {}
    while pos < len(data):
        hdr = data[pos:pos + 60]
        name = hdr[:16].decode().strip().rstrip("/")
        size = int(hdr[48:58].decode().strip())
        out[name] = data[pos + 60:pos + 60 + size]
        pos += 60 + size + (size & 1)
    return out


def _data_tar(deb: bytes) -> bytes:
    members = _ar_members(deb)
    for name, blob in members.items():
        if name.startswith("data.tar"):
            if name.endswith(".xz"):
                return lzma.decompress(blob)
            if name.endswith(".zst"):
                return subprocess.run(["zstd", "-dc"], input=blob, check=True,
                                      stdout=subprocess.PIPE).stdout
            if name.endswith(".tar"):
                return blob
            raise SystemExit(f"unsupported member {name}")
    raise SystemExit("no data.tar member")


def _unpack(tar_bytes: bytes, root: Path) -> None:
    with tarfile.open(fileobj=io.BytesIO(tar_bytes), mode="r:") as tf:
        for m in tf.getmembers():
            rel = os.path.normpath(m.name)
            if rel in (".", "") or rel.startswith(".."):
                continue
            dest = root / rel
            if m.isdir():
                dest.mkdir(parents=True, exist_ok=True)
                os.chmod(dest, m.mode & 0o7777)
            elif m.issym():
                dest.parent.mkdir(parents=True, exist_ok=True)
                if dest.is_symlink() or dest.exists():
                    dest.unlink()
                os.symlink(m.linkname, dest)
            elif m.islnk():
                src = root / os.path.normpath(m.linkname)
                if dest.exists() or dest.is_symlink():
                    dest.unlink()
                os.link(src, dest)
            elif m.isfile():
                dest.parent.mkdir(parents=True, exist_ok=True)
                if dest.is_symlink() or dest.exists():
                    dest.unlink()
                with tf.extractfile(m) as src, open(dest, "wb") as out:
                    shutil.copyfileobj(src, out)
                os.chmod(dest, m.mode & 0o7777)
            else:
                raise SystemExit(f"unsupported tar member type in {m.name}")


def install(lock: Path, root: Path, cache: Path) -> None:
    fields = read_lock(lock)
    snapshot = fields["archive_snapshot"][0]
    if root.exists() and any(root.iterdir()):
        raise SystemExit(f"{root} is not empty")
    root.mkdir(parents=True, exist_ok=True)
    cache.mkdir(parents=True, exist_ok=True)
    # Unpack in name order, so that a file shipped by two packages resolves
    # the same way every time.
    for line in sorted(fields["package"]):
        name, version, sha, filename = line.split()
        deb_path = cache / Path(filename).name
        if not deb_path.exists() or _sha256(deb_path.read_bytes()) != sha:
            deb_path.write_bytes(_fetch(f"{SNAPSHOT_BASE}/{snapshot}/{filename}"))
        data = deb_path.read_bytes()
        if _sha256(data) != sha:
            raise SystemExit(f"{name} {version}: package SHA-256 differs from the lock")
        _unpack(_data_tar(data), root)
    _post_install(root)


def _post_install(root: Path) -> None:
    etc = root / "etc"
    passwd = (root / "usr/share/base-passwd/passwd.master").read_text()
    group = (root / "usr/share/base-passwd/group.master").read_text()
    for name, uid in BUILD_USERS:
        passwd += f"{name}:x:{uid}:{uid}:rp11-launch build user:/nonexistent:/usr/sbin/nologin\n"
        group += f"{name}:x:{uid}:\n"
    for path, text in ((etc / "passwd", passwd), (etc / "group", group)):
        path.write_text(text)
        os.chmod(path, 0o644)
    for d in ("tmp", "var/tmp"):
        p = root / d
        p.mkdir(parents=True, exist_ok=True)
        if any(p.iterdir()):
            raise SystemExit(f"/{d} is not empty after unpacking")
        os.chmod(p, 0o1777)
    for mp in MOUNT_POINTS:
        (root / mp).mkdir(parents=True, exist_ok=True)
    for d in ("rp11", "rp11/alt", *MOUNT_POINTS):
        os.chmod(root / d, 0o755)
    os.chmod(root, 0o755)
    if (root / "etc/ld.so.preload").exists():
        raise SystemExit("/etc/ld.so.preload must be absent")


def main(argv: list[str]) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    sub = p.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("resolve")
    r.add_argument("--snapshot", required=True)
    r.add_argument("--suite", default="resolute")
    r.add_argument("--cache", type=Path, required=True)
    i = sub.add_parser("install")
    i.add_argument("--lock", type=Path, default=LOCK)
    i.add_argument("--root", type=Path, required=True)
    i.add_argument("--cache", type=Path, required=True)
    args = p.parse_args(argv)
    if args.cmd == "resolve":
        for line in resolve(load_index(args.snapshot, args.suite, args.cache)):
            print(line)
    else:
        install(args.lock, args.root, args.cache)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
